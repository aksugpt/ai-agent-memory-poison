def flatten(d: dict) -> tuple[list[str], list[str]]:
    """Turn {label: [texts]} into two parallel lists: all the texts, and the label of each one."""
    texts, labels = [], []
    for label, items in d.items():
        for t in items:
            texts.append(t)
            labels.append(label)
    return texts, labels
